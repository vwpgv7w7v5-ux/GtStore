import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createApp } from '../../apps/api-v6/src/app.js';

const dir=await fs.mkdtemp(path.join(os.tmpdir(),'gt-analytics-'));
const db=path.join(dir,'db.json');
const {server}=createApp({databaseFile:db,mediaDirectory:path.join(dir,'uploads'),fetch:async()=>({ok:true,json:async()=>({ok:true,result:{id:1,username:'bot'}})})});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}/api/v6`;
const request=async(url,options={})=>{const res=await fetch(base+url,{...options,headers:{'content-type':'application/json',...(options.headers||{})}});const body=res.status===204?null:await res.json();if(!res.ok)throw new Error(JSON.stringify(body));return body};
await request('/bootstrap',{method:'POST',body:JSON.stringify({email:'owner@test.local',password:'Password123!',name:'Owner'})});
const login=await request('/auth/login',{method:'POST',body:JSON.stringify({email:'owner@test.local',password:'Password123!'})});
const auth={authorization:`Bearer ${login.token}`};
const me=await request('/me',{headers:auth});
const workspace=me.workspaces[0];
let shops=await request(`/workspaces/${workspace.id}/shops`,{headers:auth});
const shop=shops[0]||await request(`/workspaces/${workspace.id}/shops`,{method:'POST',headers:auth,body:JSON.stringify({name:'Analytics Shop',slug:'analytics-shop'})});
await request(`/public/storefronts/${shop.slug}/analytics/events`,{method:'POST',body:JSON.stringify({type:'visit',source:'telegram',sessionId:'s1'})});
await request(`/public/storefronts/${shop.slug}/analytics/events`,{method:'POST',body:JSON.stringify({type:'product_view',source:'telegram',sessionId:'s1'})});
const analytics=await request(`/workspaces/${workspace.id}/shops/${shop.id}/analytics?days=30`,{headers:auth});
assert.equal(analytics.metrics.visits,1);
assert.equal(analytics.metrics.productViews,1);
assert.equal(analytics.funnel[0].value,1);
assert.equal(analytics.range.days,30);
assert.ok(Array.isArray(analytics.series));
server.close();
console.log('V6.13 analytics tests passed');
